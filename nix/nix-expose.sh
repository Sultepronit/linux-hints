#!/bin/sh

# Перевіряємо, чи передали назву програми як аргумент
if [ -z "$1" ]; then
    echo "❌ Помилка: Вкажіть назву програми. Приклад: ./make-sudo.sh go"
    exit 1
fi

APP_NAME=$1

# Знаходимо повний шлях до програми з ВАШОГО (не рутового) оточення
APP_PATH=$(which "$APP_NAME" 2>/dev/null)

# Перевіряємо, чи взагалі така програма є в Nix/Home Manager
if [ -z "$APP_PATH" ]; then
    echo "❌ Помилка: Програму '$APP_NAME' не знайдено у вашому PATH."
    echo "Перевірте, чи вона встановлена і чи правильно написана назва."
    exit 1
fi

echo "🔍 Знайдено нікс-шлях: $APP_PATH"
echo "🚀 Створюємо символічне посилання у /usr/local/bin/$APP_NAME..."

# Створюємо лінк через sudo
# Прапорець -f (force) потрібен, щоб перезаписати лінк, якщо він там уже колись був
sudo ln -sf "$APP_PATH" "/usr/local/bin/$APP_NAME"

# Перевіряємо статус виконання команди
if [ $? -eq 0 ]; then
    echo "✅ Успіх! Тепер root та системні сервіси бачать '$APP_NAME' як рідну."
else
    echo "❌ Щось пішло не так при створенні посилання."
fi
